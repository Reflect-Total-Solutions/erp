import { NextRequest, NextResponse } from "next/server";
import * as XLSX from "xlsx";
import { getSession } from "@/lib/auth";
import { checkSessionPermission } from "@/lib/permissions";
import { generateProfitLossReport } from "@/lib/profit-loss-report";

// GET /api/reports/profit-loss/export
// Generates a multi-sheet .xlsx Profit & Loss report directly from saved PostgreSQL records.
export async function GET(req: NextRequest) {
  try {
    const session = await getSession();
    if (!session) {
      return NextResponse.json(
        { success: false, error: "Unauthorized access. Please log in." },
        { status: 401 }
      );
    }

    const [canView, canViewFin, canExport, canDownload] = await Promise.all([
      checkSessionPermission(session, "profitLoss", "view"),
      checkSessionPermission(session, "profitLoss", "viewFinancials"),
      checkSessionPermission(session, "profitLoss", "export"),
      checkSessionPermission(session, "profitLoss", "download"),
    ]);

    if (!canView || !canViewFin || (!canExport && !canDownload)) {
      return NextResponse.json(
        {
          success: false,
          error: "Forbidden: You do not have permission to export Financial / Profit & Loss reports.",
        },
        { status: 403 }
      );
    }

    const { searchParams } = new URL(req.url);
    const report = await generateProfitLossReport(session, {
      search: searchParams.get("search") || undefined,
      status: searchParams.get("status") || "all",
      jobStatus: searchParams.get("jobStatus") || "all",
      jobId: searchParams.get("jobId") || "all",
      clientName: searchParams.get("clientName") || "all",
      dateFrom: searchParams.get("dateFrom") || undefined,
      dateTo: searchParams.get("dateTo") || undefined,
      createdBy: searchParams.get("createdBy") || undefined,
    });

    const wb = XLSX.utils.book_new();

    // Sheet 1: Executive Summary
    const summaryRows = [
      { Metric: "Generated By", Value: session.email || session.userId },
      { Metric: "Generated At", Value: new Date().toISOString() },
      { Metric: "Jobs Included", Value: report.summary.totalJobsCount },
      {
        Metric: "Approved Job Revenue Total (LKR)",
        Value: Number(report.summary.totalApprovedValue.toFixed(2)),
      },
      {
        Metric: "Original Estimated Job Cost Total (LKR)",
        Value: Number(report.summary.totalOriginalEstimatedCost.toFixed(2)),
      },
      {
        Metric: "Actual Supplier Invoice Cost Total (LKR)",
        Value: Number(report.summary.totalSupplierCost.toFixed(2)),
      },
      {
        Metric: "Additional Job Expenses Total (LKR)",
        Value: Number(report.summary.totalAdditionalExpenses.toFixed(2)),
      },
      {
        Metric: "Total Actual Expenses (Supplier Invoices + Additional Expenses)",
        Value: Number(report.summary.totalActualCost.toFixed(2)),
      },
      {
        Metric: "Cost Saving vs Original Job Cost (Informational)",
        Value: Number(report.summary.totalCostSaving.toFixed(2)),
      },
      {
        Metric: "Cost Overrun vs Original Job Cost",
        Value: Number(report.summary.totalCostOverrun.toFixed(2)),
      },
      {
        Metric: "Gross Profit (Revenue - Total Actual Expenses)",
        Value: Number(report.summary.totalGrossProfit.toFixed(2)),
      },
      {
        Metric: "Overall Profit Margin (%)",
        Value:
          report.summary.averageProfitMargin !== null
            ? Number(report.summary.averageProfitMargin.toFixed(2))
            : "N/A",
      },
      {
        Metric: "Supplier Payments Settled (Cashflow)",
        Value: Number(report.summary.totalSupplierPaid.toFixed(2)),
      },
      {
        Metric: "Outstanding Supplier Balance (Payables)",
        Value: Number(report.summary.totalSupplierOutstanding.toFixed(2)),
      },
    ];
    const wsSummary = XLSX.utils.json_to_sheet(summaryRows);
    XLSX.utils.book_append_sheet(wb, wsSummary, "Executive Summary");

    // Sheet 2: Job Profit & Loss Schedule
    const jobRows = report.rows.map((r) => ({
      "Job Number": r.jobCode,
      "Job Name": r.jobName,
      Client: r.clientName,
      "Job Date": r.jobDate,
      "Job Status": r.status,
      "Approved Job Revenue": Number(r.approvedJobValue.toFixed(2)),
      "Original Estimated Cost": Number(r.originalEstimatedCost.toFixed(2)),
      "Supplier Invoice Cost": Number(r.totalSupplierCost.toFixed(2)),
      "Additional Expenses": Number(r.additionalExpenses.toFixed(2)),
      "Total Actual Expenses": Number(r.totalActualCost.toFixed(2)),
      "Cost Saving": Number(r.costSaving.toFixed(2)),
      "Cost Overrun": Number(r.costOverrun.toFixed(2)),
      "Gross Profit": Number(r.grossProfit.toFixed(2)),
      "Profit Margin (%)":
        r.profitMargin !== null ? Number(r.profitMargin.toFixed(2)) : "N/A",
      "Financial Status": r.financialStatus,
      "Active Invoices": r.supplierInvoicesCount,
      "Supplier Paid": Number(r.supplierPaidAmount.toFixed(2)),
      "Outstanding Payable": Number(r.supplierOutstandingBalance.toFixed(2)),
    }));
    const wsJobs = XLSX.utils.json_to_sheet(
      jobRows.length > 0
        ? jobRows
        : [{ Info: "No matching Job financial records found for selected filters." }]
    );
    XLSX.utils.book_append_sheet(wb, wsJobs, "Job Profit & Loss");

    // Sheet 3: Additional Expenses Breakdown
    const expenseRows: any[] = [];
    for (const r of report.rows) {
      for (const exp of r.additionalExpensesBreakdown) {
        expenseRows.push({
          "Job Number": r.jobCode,
          "Job Name": r.jobName,
          "Expense Date": exp.expenseDate,
          Category: exp.category,
          Description: exp.description,
          "Supplier / Payee": exp.payee,
          "Payment Reference": exp.paymentReference,
          "Amount (LKR)": Number(exp.amount.toFixed(2)),
        });
      }
    }
    const wsExpenses = XLSX.utils.json_to_sheet(
      expenseRows.length > 0
        ? expenseRows
        : [{ Info: "No active additional expenses for selected jobs." }]
    );
    XLSX.utils.book_append_sheet(wb, wsExpenses, "Additional Expenses");

    // Sheet 4: Supplier Invoices & Payables
    const invoiceRows: any[] = [];
    for (const r of report.rows) {
      for (const inv of r.invoiceBreakdown) {
        invoiceRows.push({
          "Job Number": r.jobCode,
          "Job Name": r.jobName,
          "Invoice Number": inv.invoiceNumber,
          Supplier: inv.supplierName,
          "Invoice Date": inv.invoiceDate,
          "Due Date": inv.dueDate || "—",
          "Invoice Amount": Number(inv.totalAmount.toFixed(2)),
          "Paid Amount": Number(inv.paidAmount.toFixed(2)),
          "Outstanding Balance": Number(inv.outstandingBalance.toFixed(2)),
          "Payment Status": inv.paymentStatus,
        });
      }
    }
    const wsInvoices = XLSX.utils.json_to_sheet(
      invoiceRows.length > 0
        ? invoiceRows
        : [{ Info: "No active supplier invoices for selected jobs." }]
    );
    XLSX.utils.book_append_sheet(wb, wsInvoices, "Supplier Invoices");

    const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx" }) as Buffer;
    const dateStamp = new Date().toISOString().split("T")[0];

    return new NextResponse(new Uint8Array(buffer), {
      status: 200,
      headers: {
        "Content-Type":
          "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "Content-Disposition": `attachment; filename="Profit_Loss_Analysis_${dateStamp}.xlsx"`,
        "Cache-Control": "no-store",
      },
    });
  } catch (err: any) {
    console.error("GET /api/reports/profit-loss/export error:", err);
    return NextResponse.json(
      {
        success: false,
        error: err?.message || "Failed to export Profit & Loss Excel report.",
      },
      { status: 500 }
    );
  }
}
